import json, sys
d = json.load(open(sys.argv[1]))
W, H = d["w"], d["h"]
paths = d["paths"]
# Timeline: strokes start in left-to-right order; each draws for a time
# proportional to its length, overlapping slightly like a moving pen.
total_len = sum(max(p["len"], 1) for p in paths)
TOTAL = 2.0  # seconds of drawing
t = 0.0
rows = []
for p in paths:
    dur = max(0.03, TOTAL * max(p["len"], 1) / total_len)
    rows.append((p["d"], round(t, 3), round(dur, 3)))
    t += dur * 0.8
lines = ",\n".join(f'  ["{d_}", {delay}, {dur}]' for d_, delay, dur in rows)
src = f'''/**
 * Owner's handwritten signature, traced to centre-line strokes from the
 * supplied image (October 2026). Each entry is [path, delay s, duration s],
 * ordered left to right so the signature draws like a moving pen.
 * Generated by tools/signature/trace.py — regenerate rather than hand-edit.
 */
export const signatureViewBox = "0 0 {W} {H}";
export const signatureStroke = {d["stroke"]};
export const signatureStrokes: readonly (readonly [string, number, number])[] = [
{lines},
];
'''
open(sys.argv[2], "w").write(src)
print("strokes", len(rows), "ends at", round(t, 2))
