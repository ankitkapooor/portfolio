"""Trace pen paths through phrases rendered in the Ankit Hand font.

The paths are used as a mask that reveals the real font text stroke by
stroke, so they only need to cover the letters, in writing order.
"""
import json, os, re, sys
import numpy as np
from PIL import Image
sys.path.insert(0, sys.argv[1])
from strokes import trace, path_d, poly_len

render_dir, json_dir, ts_out = sys.argv[2], sys.argv[3], sys.argv[4]
meta = json.load(open(f"{render_dir}/meta.json"))
os.makedirs(json_dir, exist_ok=True)
ASC, BOX = 850, 1170

def slug(text):
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")

def relative(path):
    nums = [float(v) for v in re.findall(r"-?\d+(?:\.\d+)?", path)]
    if path.endswith("h1"):
        return f"M{round(nums[0])} {round(nums[1])}h1"
    x, y = round(nums[0]), round(nums[1])
    vals = []
    for i in range(2, len(nums) - 5, 6):
        c = [round(v) for v in nums[i:i + 6]]
        vals += [c[0] - x, c[1] - y, c[2] - x, c[3] - y, c[4] - x, c[5] - y]
        x, y = c[4], c[5]
    s = ""
    for v in vals:
        s += str(v) if (v < 0 or not s) else " " + str(v)
    return f"M{round(nums[0])} {round(nums[1])}c" + s

rows, total = [], 0
for text, m in meta.items():
    img = np.asarray(Image.open(f"{render_dir}/{m['file']}").convert("L"))
    ink = img < 140
    polys, stroke = trace(ink, smooth=2.0, rdp_eps=3.0)
    k = 1000 / m["F"]
    # canvas px -> font units; box origin is (pad, baseline - ascent)
    ox, oy = m["pad"], m["baseline"] - ASC / k
    P = [[((x - ox) * k, (y - oy) * k) for x, y in poly] for poly in polys]
    lens = [poly_len(poly) for poly in P]
    T = min(2.2, max(0.8, m["advance"] * k / 1000 * 0.18))
    t, strokes = 0.0, []
    total_len = sum(max(l, 1) for l in lens)
    for poly, length in zip(P, lens):
        dur = max(0.03, T * max(length, 1) / total_len)
        strokes.append([relative(path_d(poly)), t, t + dur])
        t += dur * 0.8
    # Fragments get a minimum duration, which can stretch long phrases; scale
    # the whole timeline back to the target writing time.
    end = max(s[2] for s in strokes)
    strokes = [[d, a * T / end, b * T / end] for d, a, b in strokes]
    end = T
    data = {
        "t": round(end, 2),
        # Mask pen: wider than the letter strokes so the reveal covers them.
        "m": round(stroke * k * 2.1),
        "s": [[d, round(a / end, 3), round(min(1, b / end), 3)] for d, a, b in strokes],
    }
    blob = json.dumps(data, separators=(",", ":"))
    open(f"{json_dir}/{slug(text)}.json", "w").write(blob)
    total += len(blob)
    rows.append(f'  {json.dumps(text)}: {{ id: "{slug(text)}", w: {round(m["advance"] * k)} }},')

open(ts_out, "w").write(f'''/**
 * Phrases that write themselves in the "Ankit Hand" font.
 *
 * The font (app/fonts/AnkitHand-Regular.woff2) is the owner's handwriting,
 * cleaned into consistent letterforms. For each phrase listed here, pen paths
 * traced through the font's own letters (public/hand/<id>.json) drive a mask
 * that reveals the real text stroke by stroke. Widths are the font's advance
 * in units of 1000 per em; the box is the font's ascent ({ASC}) plus descent.
 *
 * Generated by tools/handwriting/trace_font.py from tools/handwriting/
 * phrases.json — add a phrase there and regenerate rather than hand-editing.
 */
export type HandPhraseBox = {{ id: string; w: number }};

export const handAscent = {ASC};
export const handBox = {BOX};

export const handPhrases: Record<string, HandPhraseBox> = {{
{chr(10).join(rows)}
}};
''')
print("phrases", len(rows), "json bytes", total)
